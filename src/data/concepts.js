// ---------- step builders for the two "row by row" animations ----------

function runningTotalSteps() {
  const totals = [10, 30, 60, 80, 120];
  const steps = [{ caption: "Start with sales per day.", tables: [table("daily_sales", DAILY_COLS, DAILY, { id: "main" })] }];
  DAILY.forEach((_, d) => {
    const parts = DAILY.slice(0, d + 1).map((r) => r[1]);
    steps.push({
      caption: `Day ${d + 1}: ${parts.join(" + ")} = ${totals[d]}. Add every row from the top down to this one.`,
      tables: [table("daily_sales", [...DAILY_COLS, "running_total"], DAILY.map((r, i) => [...r, i <= d ? totals[i] : ""]), {
        id: "main",
        marks: DAILY.map((_, i) => (i <= d ? "g1" : "")),
        colMarks: { 2: "new" },
      })],
    });
  });
  return steps;
}

function movingAverageSteps() {
  const avgs = [10, 15, 20, 23.3, 30];
  const steps = [{ caption: "Start with sales per day. The window is 3 rows: this row + 2 before it.", tables: [table("daily_sales", DAILY_COLS, DAILY, { id: "main" })] }];
  DAILY.forEach((_, d) => {
    const from = Math.max(0, d - 2);
    const parts = DAILY.slice(from, d + 1).map((r) => r[1]);
    steps.push({
      caption: `Day ${d + 1}: the window covers ${parts.length} row${parts.length > 1 ? "s" : ""}. (${parts.join(" + ")}) / ${parts.length} = ${avgs[d]}.`,
      tables: [table("daily_sales", [...DAILY_COLS, "moving_avg_3"], DAILY.map((r, i) => [...r, i <= d ? avgs[i] : ""]), {
        id: "main",
        marks: DAILY.map((_, i) => (i >= from && i <= d ? "g1" : "")),
        colMarks: { 2: "new" },
      })],
    });
  });
  return steps;
}

